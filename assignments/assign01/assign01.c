#include <stdio.h>
#include "pico/stdlib.h"
#include "hardware/gpio.h"
#include "hardware/pio.h"
#include "ws2812.pio.h"

#define IS_RGBW true
#define NUM_PIXELS 1
#define WS2812_PIN 28

// Must declare the main assembly entry point before use.
void main_asm();

// Initialise a GPIO pin - see SDK for detail on gpio_init()
void asm_gpio_init(uint pin){
    gpio_init(pin);
}

// Set direction of a GPIO pin - see SDK for detail on gpio_set_dir()
void asm_gpio_set_dir(uint pin, bool out){
    gpio_set_dir(pin, out);
}

// Get the value of a GPIO pin - see SDK for detail on gpio_set_dir()
bool asm_gpio_get(uint pin){
    return gpio_get(pin);
}

// Set the value of a GPIO pin - see SDK for detail on gpio_put()
void asm_gpio_put(uint pin, bool value) {
    gpio_put(pin, value);
}

// Enable falling-edge interrupt - see SDK for detail on gpio_set_irq_enabled()
void asm_gpio_set_irq(uint pin) {
    gpio_set_irq_enabled(pin, GPIO_IRQ_EDGE_FALL, true);
}

/**
 * @brief Wrapper function used to call the underlying PIO
 *        function that pushes the 32-bit RGB colour value
 *        out to the LED serially using the PIO0 block. The
 *        function does not return until all of the data has
 *        been written out.
 *
 * @param pixel_grb The 32-bit colour value generated by urgb_u32()
 */
static inline void put_pixel(uint32_t pixel_grb)
{
    pio_sm_put_blocking(pio0, 0, pixel_grb << 8u);
}

/**
 * @brief Function to generate an unsigned 32-bit composit GRB
 *        value by combining the individual 8-bit paramaters for
 *        red, green and blue together in the right order.
 *
 * @param r     The 8-bit intensity value for the red component
 * @param g     The 8-bit intensity value for the green component
 * @param b     The 8-bit intensity value for the blue component
 * @return uint32_t Returns the resulting composit 32-bit RGB value
 */
static inline uint32_t urgb_u32(uint8_t r, uint8_t g, uint8_t b)
{
    return ((uint32_t)(r) << 8) | ((uint32_t)(g) << 16) | (uint32_t)(b);
}

void asm_set_led_color(uint8_t index)
{
    switch (index)
    {
    case 0:
        put_pixel(urgb_u32(0x00, 0x00, 0x00));
        break;
    case 1:
        put_pixel(urgb_u32(0x7F, 0x00, 0x00));
        break;
    case 2:
        put_pixel(urgb_u32(0x00, 0x7F, 0x00));
        break;
    case 3:
        put_pixel(urgb_u32(0x00, 0x00, 0x7F));
        break;
    case 4:
        put_pixel(urgb_u32(0x7F, 0x7F, 0x00));
        break;
    default:
        break;
    }
}

/*
 * Main entry point for the code - simply calls the main assembly function.
 */
int main()
{
    stdio_init_all();
    PIO pio = pio0;
    uint offset = pio_add_program(pio, &ws2812_program);
    ws2812_program_init(pio, 0, offset, WS2812_PIN, 800000, IS_RGBW);
    printf("Assignment #01 with RGB Features...\n");
    main_asm();

    return 0;
}